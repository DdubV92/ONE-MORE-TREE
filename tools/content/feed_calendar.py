"""Simulates the Phase 17 feed publication calendar outside the engine and
writes docs/editorial/FEED_CALENDAR.md.

Mirrors FeedService: units publish in (day, slot, at) order; mx branches
take one side per campaign (both sides are reported); if:/unless: flags are
evaluated when due (reported both ways: the default campaign with every flag
false, and the union of everything reachable on some path); parents gate
replies; cl01 either stages (warning) or uses its fallback; at most 240
units count against one day (the rest roll to the next day).

  python3 tools/content/feed_calendar.py
"""
import json, os, glob

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CAP = 240
SLOT = {"day": 0, "dusk": 900, "night": 1200}


def load():
    units = []
    for f in sorted(glob.glob(os.path.join(ROOT, "data/feed/*.json"))):
        if f.endswith("accounts.json"):
            continue
        for u in json.load(open(f, encoding="utf-8")).get("units", []):
            units.append(u)
    units.sort(key=lambda u: (u["day"], SLOT[u["slot"]] + u["at"], u["id"]))
    return units


def simulate(units, mx_side, flags, cl01_ok):
    pub, day_count, deferred = {}, {}, []
    for day in range(1, 36):
        # roll deferred first
        keep = []
        for u in deferred:
            if day_count.get(day, 0) < CAP:
                pub[u["id"]] = day
                day_count[day] = day_count.get(day, 0) + 1
            else:
                keep.append(u)
        deferred = keep
        for u in [x for x in units if x["day"] == day]:
            b = u.get("branch", "")
            if b.startswith("mx:") and b.split(":")[2] != mx_side:
                continue
            if b.startswith("if:") and not flags.get(b[3:], False):
                continue
            if b.startswith("unless:") and flags.get(b[7:], False):
                continue
            if b == "fallback:cl01" and cl01_ok:
                continue
            if u.get("parent") and u["parent"] not in pub:
                continue
            if u.get("hook") == "cl01" and not cl01_ok:
                continue
            if day_count.get(day, 0) >= CAP:
                deferred.append(u)
                continue
            pub[u["id"]] = day
            day_count[day] = day_count.get(day, 0) + 1
    return pub, day_count, deferred


def main():
    units = load()
    by_id = {u["id"]: u for u in units}
    flags_all = {f: True for f in ["wages_owed", "worker_left", "dog_rescued", "truck_owned", "saw_owned", "cleared25", "cleared50", "cleared75", "late_reader", "night_event", "hunt", "rescue"]}
    runs = {
        "default (side a, no flags, cl01 fallback)": simulate(units, "a", {}, False),
        "side b, no flags": simulate(units, "b", {}, False),
        "side a, all flags, cl01 staged": simulate(units, "a", flags_all, True),
    }
    reach = set()
    for k, (pub, _, _) in runs.items():
        reach |= set(pub)
    unreachable = [u["id"] for u in units if u["id"] not in reach]
    mx = [u for u in units if u.get("branch", "").startswith("mx:")]
    cond = [u for u in units if u.get("branch", "").startswith(("if:", "unless:", "fallback:"))]
    lines = ["# Feed publication calendar (generated by tools/content/feed_calendar.py)", ""]
    lines.append("Authored units: %d. Mutually exclusive (mx) units: %d. Conditional (if/unless/fallback) units: %d. Unreachable on every simulated path: %d." % (len(units), len(mx), len(cond), len(unreachable)))
    lines.append("")
    for k, (pub, dc, deferred) in runs.items():
        lines.append("## %s" % k)
        lines.append("")
        lines.append("Published: %d. Max per day: %d (cap %d). Left over after day 35: %d." % (len(pub), max(dc.values()) if dc else 0, CAP, len(deferred)))
        lines.append("")
        lines.append("| Day | Units | Mail | News | Forum | Advisory | Archive |")
        lines.append("|---:|---:|---:|---:|---:|---:|---:|")
        for d in range(1, 36):
            ids = [i for i, dd in pub.items() if dd == d]
            if not ids:
                continue
            kinds = {}
            for i in ids:
                kinds[by_id[i]["kind"]] = kinds.get(by_id[i]["kind"], 0) + 1
            lines.append("| %d | %d | %d | %d | %d | %d | %d |" % (d, len(ids), kinds.get("mail", 0), kinds.get("news", 0), kinds.get("forum", 0), kinds.get("advisory", 0), kinds.get("archive", 0)))
        lines.append("")
    lines.append("## Branches")
    lines.append("")
    groups = {}
    for u in mx:
        g = u["branch"].split(":")[1]
        groups.setdefault(g, {"a": 0, "b": 0})[u["branch"].split(":")[2]] += 1
    for g, c in sorted(groups.items()):
        lines.append("- mx group `%s`: side a %d units, side b %d units (one side per campaign)" % (g, c["a"], c["b"]))
    fl = {}
    for u in cond:
        fl[u["branch"]] = fl.get(u["branch"], 0) + 1
    for b, n in sorted(fl.items()):
        lines.append("- `%s`: %d units" % (b, n))
    hooks = {}
    for u in units:
        if u.get("hook"):
            hooks.setdefault(u["hook"], []).append(u["id"])
    lines.append("")
    lines.append("## Computer-linked hooks")
    lines.append("")
    for h in sorted(hooks):
        lines.append("- `%s`: %s%s" % (h, ", ".join(hooks[h]), " (implemented: director reservation + fallback)" if h == "cl01" else " (Phase 19 mapping; recorded as an opportunity)"))
    if unreachable:
        lines.append("")
        lines.append("## Unreachable units")
        lines.append("")
        lines.append(", ".join(unreachable[:200]))
    out = os.path.join(ROOT, "docs/editorial/FEED_CALENDAR.md")
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    d = runs["default (side a, no flags, cl01 fallback)"]
    print("UNITS", len(units), "REACHABLE", len(reach), "UNREACHABLE", len(unreachable), "DEFAULT_PUBLISHED", len(d[0]), "MAX_DAY", max(d[1].values()) if d[1] else 0)


main()
