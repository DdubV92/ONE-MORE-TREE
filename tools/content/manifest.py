"""Writes docs/editorial/CONTENT_MANIFEST.md: every content batch with its
category, counts, review state and the validators' output (parsed data,
not estimates).

  python3 tools/content/manifest.py
"""
import json, os, glob, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def run(script):
    p = subprocess.run([sys.executable, os.path.join(ROOT, "tools/content", script)], capture_output=True, text=True)
    return p.returncode, p.stdout.strip()


def main():
    out = ["# Content manifest (generated by tools/content/manifest.py)", ""]
    out.append("## Crew dialogue bank (`data/dialogue/crew/`)")
    out.append("")
    out.append("| Batch file | Category | Lines | Marta | Dale | Priya | Tomas | Joan | Role/trait | Review |")
    out.append("|---|---|---:|---:|---:|---:|---:|---:|---:|---|")
    tot = {"lines": 0}
    for f in sorted(glob.glob(os.path.join(ROOT, "data/dialogue/crew/*.json"))):
        d = json.load(open(f, encoding="utf-8"))
        ls = d.get("lines", [])
        sp = {}
        for ln in ls:
            sp[ln.get("speaker")] = sp.get(ln.get("speaker"), 0) + 1
        role = sum(v for k, v in sp.items() if not str(k).startswith("EMP-"))
        out.append("| %s | %s | %d | %d | %d | %d | %d | %d | %d | %s |" % (os.path.basename(f), d.get("category", ""), len(ls), sp.get("EMP-01", 0), sp.get("EMP-02", 0), sp.get("EMP-03", 0), sp.get("EMP-04", 0), sp.get("EMP-05", 0), role, d.get("review", "draft")))
        tot["lines"] += len(ls)
        for k, v in sp.items():
            tot[k] = tot.get(k, 0) + v
    out.append("| **total** | | **%d** | %d | %d | %d | %d | %d | %d | |" % (tot["lines"], tot.get("EMP-01", 0), tot.get("EMP-02", 0), tot.get("EMP-03", 0), tot.get("EMP-04", 0), tot.get("EMP-05", 0), sum(v for k, v in tot.items() if k != "lines" and not str(k).startswith("EMP-"))))
    rc, txt = run("validate_crew.py")
    out += ["", "Validator (`tools/content/validate_crew.py`, exit %d):" % rc, "", "```", txt, "```", ""]
    out.append("## Fictional internet (`data/feed/`)")
    out.append("")
    out.append("| Batch file | Units | Mail | News | Forum | Advisory | Archive | Days | Review |")
    out.append("|---|---:|---:|---:|---:|---:|---:|---|---|")
    ft = {}
    n = 0
    for f in sorted(glob.glob(os.path.join(ROOT, "data/feed/*.json"))):
        if f.endswith("accounts.json"):
            continue
        d = json.load(open(f, encoding="utf-8"))
        us = d.get("units", [])
        k = {}
        days = set()
        for u in us:
            k[u["kind"]] = k.get(u["kind"], 0) + 1
            ft[u["kind"]] = ft.get(u["kind"], 0) + 1
            days.add(u["day"])
        n += len(us)
        out.append("| %s | %d | %d | %d | %d | %d | %d | %s | %s |" % (os.path.basename(f), len(us), k.get("mail", 0), k.get("news", 0), k.get("forum", 0), k.get("advisory", 0), k.get("archive", 0), "%d-%d" % (min(days), max(days)) if days else "-", d.get("review", "draft")))
    out.append("| **total** | **%d** | %d | %d | %d | %d | %d | | |" % (n, ft.get("mail", 0), ft.get("news", 0), ft.get("forum", 0), ft.get("advisory", 0), ft.get("archive", 0)))
    acc = json.load(open(os.path.join(ROOT, "data/feed/accounts.json"), encoding="utf-8"))["accounts"]
    out += ["", "Accounts: %d (`data/feed/accounts.json`)." % len(acc)]
    rc, txt = run("validate_feed.py")
    out += ["", "Validator (`tools/content/validate_feed.py`, exit %d):" % rc, "", "```", "\n".join(txt.splitlines()[:30]), "```", ""]
    rc, txt = run("feed_calendar.py")
    out += ["Calendar simulation (`tools/content/feed_calendar.py`, see FEED_CALENDAR.md): " + txt, ""]
    open(os.path.join(ROOT, "docs/editorial/CONTENT_MANIFEST.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("crew", tot["lines"], "feed", n, "accounts", len(acc))


main()
