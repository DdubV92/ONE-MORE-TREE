"""Builds the Phase 15 original sound library into audio/lib/<category>/.

  python3 tools/audio_lib/build.py            # all sources
  python3 tools/audio_lib/build.py axe_bite   # names containing a substring

One-shots: 16-bit mono WAV at 32 kHz (cached, short, crisp contacts).
Loops: mono Ogg Vorbis (streamed, looped seamlessly; the runtime sets loop).
Writes audio/lib/manifest.json (name, category, loop, model, seconds, file,
seed, origin, license). Deterministic: seed = crc32(name).
"""
import json
import os
import sys
import zlib

import numpy as np
import soundfile as sf

sys.path.insert(0, os.path.dirname(__file__))
import dsp  # noqa: E402
from library import build_catalog  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "audio", "lib")


def main():
    only = sys.argv[1] if len(sys.argv) > 1 else ""
    cat = build_catalog()
    man_path = os.path.join(OUT, "manifest.json")
    manifest = {}
    if os.path.exists(man_path):
        manifest = json.load(open(man_path))
    for name, (category, loop, model, fn) in sorted(cat.items()):
        if only and only not in name:
            continue
        seed = zlib.crc32(name.encode()) & 0xFFFFFFFF
        g = dsp.rng(seed)
        y = np.asarray(fn(g), dtype=np.float64)
        y = y - np.mean(y)
        y = dsp.norm(y, 0.89)
        if not loop:
            # Trim leading near-silence (keep 2 ms) so contacts start on time.
            k = int(np.argmax(np.abs(y) > 0.01))
            y = y[max(k - int(0.002 * dsp.RATE), 0):]
        d = os.path.join(OUT, category)
        os.makedirs(d, exist_ok=True)
        ext = "ogg" if loop else "wav"
        path = os.path.join(d, "%s.%s" % (name, ext))
        if loop:
            sf.write(path, y, dsp.RATE, format="OGG", subtype="VORBIS")
        else:
            sf.write(path, y, dsp.RATE, subtype="PCM_16")
        manifest[name] = {"category": category, "loop": loop, "model": model, "seconds": round(len(y) / dsp.RATE, 3),
                          "file": "res://audio/lib/%s/%s.%s" % (category, name, ext), "seed": seed,
                          "origin": "original procedural synthesis (tools/audio_lib)", "license": "project original",
                          "recording": False, "auditioned": False}
    # Drop entries no longer in the catalog.
    for k in list(manifest.keys()):
        if k not in cat:
            del manifest[k]
    json.dump(manifest, open(man_path, "w"), indent=1, sort_keys=True)
    # Runtime index (GDScript constant): name -> [path, loop, category].
    lines = ["class_name SoundLibIndex", "extends RefCounted", "## GENERATED by tools/audio_lib/build.py - do not edit.", "## Phase 15 original procedural sound library (no recordings).", "", "const FILES := {"]
    for k in sorted(manifest):
        v = manifest[k]
        lines.append('\t"%s": ["%s", %s, "%s"],' % (k, v["file"], "true" if v["loop"] else "false", v["category"]))
    lines.append("}")
    open(os.path.join(ROOT, "scripts", "audio", "sound_lib_index.gd"), "w").write("\n".join(lines) + "\n")
    counts = {}
    for v in manifest.values():
        counts[v["category"]] = counts.get(v["category"], 0) + 1
    print("built", len(manifest), "sources", counts)


if __name__ == "__main__":
    main()
